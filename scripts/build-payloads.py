#!/usr/bin/env python3
"""Build version-locked React Native bundles and the private OTA bundle loader."""
import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import re
from base_config import load

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.work' / 'upstream'

def run(*args, cwd=SOURCE):
    subprocess.run(args, cwd=cwd, check=True)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--variant', choices=['wallpaper', 'storage', 'wallpaper-storage'])
    parser.add_argument('--patches-only', action='store_true', help='Build patch updates without the APK creation loader or Android SDK.')
    args = parser.parse_args()
    base, release = load()
    commit = base['commit']
    SOURCE.parent.mkdir(exist_ok=True)
    if not SOURCE.exists():
        run('git', 'clone', 'https://github.com/ByHanyou/Plural-Star.git', str(SOURCE), cwd=ROOT)
    run('git', 'fetch', 'origin', commit)
    run('git', 'checkout', '--detach', commit)
    # .work/upstream is disposable generated build state, never a user's checkout.
    run('git', 'reset', '--hard', commit)
    # Reinstall when the upstream lockfile changes, including in reused local builds.
    lock_hash = hashlib.sha256((SOURCE / 'package-lock.json').read_bytes()).hexdigest()
    installed = SOURCE / 'node_modules/.plural-lock.sha256'
    if not installed.exists() or installed.read_text() != lock_hash:
        run('npm', 'ci', '--legacy-peer-deps', '--no-audit', '--no-fund')
        installed.write_text(lock_hash)
    run('npm', 'ci', '--no-audit', '--no-fund', cwd=ROOT / 'tests')
    destination = ROOT / 'app/src/main/assets/payloads'
    destination.mkdir(parents=True, exist_ok=True)
    variants = [args.variant] if args.variant else ['wallpaper', 'storage', 'wallpaper-storage']
    for variant in variants:
        run('git', 'reset', '--hard', commit)
        # Remove only files generated by this builder, including new PR files.
        run('git', 'clean', '-fd', '--', 'src', 'scripts')
        wallpaper = 'wallpaper' in variant
        storage = 'storage' in variant
        if wallpaper:
            run('git', 'apply', str(ROOT / 'payload/wallpaper-pr-24.patch'))
        run('git', 'apply', str(ROOT / 'payload/pluralkit-pr-11.patch'))
        run('git', 'apply', str(ROOT / 'payload/no-speaker.patch'))
        run('git', 'apply', str(ROOT / 'payload/confirm-once.patch'))
        run('git', 'apply', str(ROOT / 'payload/device-unlock.patch'))
        run('git', 'apply', str(ROOT / 'payload/lock-icon.patch'))
        run('git', 'apply', str(ROOT / 'payload/extra-customization.patch'))
        run('git', 'apply', '--unidiff-zero', str(ROOT / 'payload/group-view.patch'))
        shutil.copytree(ROOT / 'payload/mods', SOURCE / 'src/mods', dirs_exist_ok=True)
        assert re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', release['version'])
        assert re.fullmatch(r'[a-z0-9.-]{1,80}', release['runtime'])
        (SOURCE / 'src/mods/modOptions.ts').write_text('export const options = ' + json.dumps({'wallpaper': wallpaper, 'storage': storage}) + ';\nexport const payloadVersion = ' + json.dumps(release['version']) + ';\nexport const patchRuntime = ' + json.dumps(release['runtime']) + ';\nexport const patchVariant = ' + json.dumps(variant) + ';\n')
        # Install the entry point into Settings for every payload combination.
        settings = SOURCE / 'src/modals/SystemModal.tsx'
        settings_text = settings.read_text()
        settings_text = "import {useAppStore} from '../store/appStore';\nimport {ModSettingsButton} from '../mods/ModMenu';\n" + settings_text
        save_settings = 'await onSaveSettings({...settings,'
        assert settings_text.count(save_settings) == 1
        settings_text = settings_text.replace(save_settings, 'await onSaveSettings({...useAppStore.getState().appSettings,')
        sheet = 'footer={<Btn instant onPress={save}>{t(\'common.save\')}</Btn>}>'
        assert settings_text.count(sheet) == 1
        settings_text = settings_text.replace(sheet, sheet + '\n      <ModSettingsButton />')
        if wallpaper:
            settings_text = settings_text.replace("import {BackgroundSection} from './system/BackgroundSection';\n", '')
            settings_text = settings_text.replace('      <BackgroundSection filename={settings.backgroundImage} onChange={onChangeBackground} />\n', '')
            settings_text = settings_text.replace('onSelectPalette, onChangeBackground, onOpenProfile', 'onSelectPalette, onOpenProfile')
            background = SOURCE / 'src/app/AppBackground.tsx'
            background_text = background.read_text()
            background_text = "import {useModPreferences} from '../mods/modPreferences';\n" + background_text
            target = '  const filename = useAppStore(s => s.appSettings.backgroundImage);'
            assert target in background_text
            background_text = background_text.replace(target, '  const enabled = useModPreferences();\n  const selected = useAppStore(s => s.appSettings.backgroundImage);\n  const filename = enabled.wallpaper ? selected : undefined;')
            background.write_text(background_text)
            translations = SOURCE / 'src/i18n/en.json'
            en = json.loads(translations.read_text())
            en['modal']['backgroundImage'] = 'Wallpaper'
            en['modal']['backgroundImageDesc'] = 'Choose a background that feels like you.'
            translations.write_text(json.dumps(en, ensure_ascii=False, indent=2) + '\n')
        else:
            (SOURCE / 'src/mods/WallpaperControls.tsx').write_text('export const WallpaperControls = () => null;\n')
        settings.write_text(settings_text)
        app = SOURCE / 'App.tsx'
        app_text = app.read_text()
        app_text = "import {PatchUpdatePrompt} from './src/mods/PatchUpdatePrompt';\nimport {useModCloudSync} from './src/mods/cloudMods';\n" + app_text
        target = '  useBackToFront(locked, loaded);'
        assert app_text.count(target) == 1
        app_text = app_text.replace(target, target + '\n  useModCloudSync(loaded && !firstRun && !locked);')
        target = '        <AppModals isSinglet={isSinglet} selfMember={selfMember} />'
        assert app_text.count(target) == 1
        app_text = app_text.replace(target, target + '\n        <PatchUpdatePrompt enabled={loaded && !firstRun && !locked} />')
        app.write_text(app_text)
        entry = SOURCE / 'index.js'
        text = entry.read_text()
        assert "import App from './App';" in text
        text = text.replace("import App from './App';", "import App from './src/mods/ModsRoot';\nimport {toolsAreOpen, runNotification} from './src/mods/toolsState';\nimport {recoverBeforeStart} from './src/mods/storageSnapshot';")
        handler = 'const handleFrontNotifEvent = allowReassert => async event => {\n  try {'
        assert handler in text
        text = text.replace(handler, 'const handleFrontNotifEvent = allowReassert => event => runNotification(async () => {\n  try {\n    await recoverBeforeStart();\n    if (toolsAreOpen()) return;')
        ending = '\n};\n\nnotifee.onBackgroundEvent'
        assert ending in text
        text = text.replace(ending, '\n});\n\nnotifee.onBackgroundEvent')
        entry.write_text(text)
        run('npm', 'run', 'typecheck')
        if wallpaper:
            run('node', '--test', 'scripts/background-settings.test.js', 'scripts/restore-settings.test.js')
        run('node', str(ROOT / 'tests/storage.test.cjs'), str(SOURCE))
        run('node', str(ROOT / 'tests/mods.test.cjs'), str(SOURCE))
        run('node', str(ROOT / 'tests/cloud-mods.test.cjs'), str(SOURCE))
        run('node', str(ROOT / 'tests/ui.test.cjs'), str(SOURCE))
        run('node', str(ROOT / 'tests/updates.test.cjs'), str(SOURCE))
        run('node', str(ROOT / 'tests/pluralkit.test.cjs'), str(SOURCE))
        run('npx', '--no-install', 'react-native', 'bundle', '--platform', 'android', '--dev', 'false',
            '--entry-file', 'index.js', '--bundle-output', str(destination / (variant + '.bundle')),
            '--assets-dest', str(ROOT / '.work' / 'bundle-assets'), '--max-workers', '2', '--reset-cache')
    if not args.patches_only:
        run('python3', str(ROOT / 'scripts/build-native-updates.py'), cwd=ROOT)
    (destination / 'provenance.json').write_text(json.dumps({'upstream': commit, 'upstream_version': base['version'], 'wallpaper_pr': 24,
        'wallpaper_commit': '72aa97e443a313016d07c9dfec4f09a06edea304',
        'pluralkit_pr': 11, 'pluralkit_commit': 'c1bd5e2f7a5fbb7934733e331154307948424cb0', 'bundle_format': 'javascript',
        'version': release['version'], 'runtime': release['runtime'],
        'bundles': {v: hashlib.sha256((destination / (v + '.bundle')).read_bytes()).hexdigest() for v in variants},
        'supported_apk_sha256': base['sha256']}, indent=2) + '\n')

if __name__ == '__main__':
    main()
